class FrameBuffer:
    # `buf` and `fmt` are accepted for signature compatibility and ignored:
    # nothing on the Kindle sends the packed buffer to a panel.
    def __init__(self, buf, width, height, fmt=MONO_VLSB):
        self.width = width
        self.height = height
        self.pixels = bytearray(width * height)

    def fill(self, c):
        self.pixels[:] = bytes([c & 1]) * len(self.pixels)

    def pixel(self, x, y, c=None):
        if not (0 <= x < self.width and 0 <= y < self.height):
            return None
        if c is None:
            return self.pixels[y * self.width + x]
        self.pixels[y * self.width + x] = c & 1
        return None

    def fill_rect(self, x, y, w, h, c):
        x0, y0 = max(0, x), max(0, y)
        x1, y1 = min(self.width, x + w), min(self.height, y + h)
        if x0 >= x1:
            return
        row = bytes([c & 1]) * (x1 - x0)
        for yy in range(y0, y1):
            start = yy * self.width + x0
            self.pixels[start : start + len(row)] = row

    def hline(self, x, y, w, c):
        self.fill_rect(x, y, w, 1, c)

    def vline(self, x, y, h, c):
        self.fill_rect(x, y, 1, h, c)

    def rect(self, x, y, w, h, c, f=False):
        if f:
            self.fill_rect(x, y, w, h, c)
            return
        self.hline(x, y, w, c)
        self.hline(x, y + h - 1, w, c)
        self.vline(x, y, h, c)
        self.vline(x + w - 1, y, h, c)

    def line(self, x1, y1, x2, y2, c):
        # One pixel per step along the longer axis. Rounding can put a pixel
        # one off from MicroPython's Bresenham; at 3x on a Kindle, invisible.
        steps = max(abs(x2 - x1), abs(y2 - y1), 1)
        for i in range(steps + 1):
            self.pixel(x1 + round((x2 - x1) * i / steps), y1 + round((y2 - y1) * i / steps), c)

    def text(self, s, x, y, c=1):
        # Glyphs are 8 column bytes, LSB at the top; only set bits are drawn,
        # so text over a fill keeps the fill behind it, as on the device.
        for ch in str(s):
            code = ord(ch)
            if not 32 <= code <= 127:
                code = 127
            glyph = _FONT[(code - 32) * 8 : (code - 32) * 8 + 8]
            for col in range(8):
                bits = glyph[col]
                for row in range(8):
                    if bits >> row & 1:
                        self.pixel(x + col, y + row, c)
            x += 8
